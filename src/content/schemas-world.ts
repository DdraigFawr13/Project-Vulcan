// Shapes of the world, magic-tier, creature and item files in src/content/data.
import { any, bool, list, map, num, obj, oneOf, opt, range, ref, str } from './schema';
import { attribute, count, id, share, text, texts } from './schema-fields';

export const WORLD_SCHEMAS = {
  calendar: obj({
    daysPerWeek: count,
    daysPerMonth: count,
    monthsPerYear: count,
    seasons: list(str()),
    monthNames: list(str()),
  }),
  tiers: list(
    obj({
      id: oneOf('none', 'faint', 'gifted', 'strong', 'exceptional', 'legendary'),
      minPower: count,
      maxPower: count,
      soldiers: range(),
      caps: obj({ maxDamage: count, maxAreaRadius: count, maxUsesPerDay: count }),
    }),
  ),
  biomes: obj({
    biomes: list(
      obj({
        id,
        name: text,
        color: list(num({ min: 0, max: 255 }), 3),
        fertility: count,
        wildness: count,
        travel: count,
        water: opt(oneOf('sea', 'coast', 'lake')),
        forest: opt(bool()),
      }),
    ),
    rules: obj({
      temperatureBands: list(num()),
      rainfallBands: list(num()),
      table: list(list(ref('biomes'))),
      alpineElevation: num(),
      frostFree: obj({
        biomes: list(ref('biomes')),
        minWinter: num(),
        fallback: map(ref('biomes'), 'biomes'),
      }),
      swampRainfall: num(),
      swampMinTemp: num(),
      coastReach: count,
    }),
  }),
  resources: list(
    obj({
      id,
      name: text,
      category: str(),
      good: opt(str()),
      minElevation: opt(num()),
      maxElevation: opt(num()),
      clustersPer10k: count,
      clusterSize: count,
      maxCellShare: share,
      needs: opt(map(any())),
      biomes: opt(list(ref('biomes'))),
      aquatic: opt(bool()),
    }),
  ),
  weather: list(
    obj({
      id,
      name: text,
      warmth: num(),
      seasonWeights: obj({ spring: count, summer: count, autumn: count, winter: count }),
    }),
  ),
  'great-works': obj({
    kinds: list(
      obj({
        id,
        word: text,
        thing: opt(bool()),
        names: texts,
        siteKinds: texts,
        features: texts,
        builder: obj({
          minPower: count,
          schools: list(ref('schools')),
          raceIds: list(ref('races')),
        }),
        cost: map(count),
      }),
    ),
    legendOrder: map(texts),
    realmOrder: texts,
    legendChance: share,
    realmChance: share,
    realmWealthMin: count,
    realmGapYears: count,
    maxPerSite: count,
    years: range(),
    epithets: texts,
    wallDefence: num(),
    wallRaidShare: share,
    bridgeWealth: num(),
    groveHarvest: num(),
    grovePlague: num(),
    towerKeepPower: count,
    fallPhrases: map(text),
    fallCauses: texts,
    enchant: any(),
  }),
  creatures: list(
    obj({
      id,
      name: text,
      tier: oneOf('beast', 'great', 'legendary'),
      biomes: list(ref('biomes')),
      minWildness: count,
      danger: count,
      maxAlive: count,
      spawnChance: share,
      lifespan: range(),
      raidChance: share,
      raidRange: count,
      roam: opt(count),
      names: texts,
    }),
  ),
  dragons: obj({
    creatureId: ref('creatures'),
    names: texts,
    tempers: list(any()),
    lairNames: texts,
    court: any(),
    // The other dragon fields are Story Generator history tuning, kept as forked.
    firstBy: num(),
    laterFirstBy: num(),
    cellsPerDragon: num(),
    maxAlive: num(),
    lairsApart: num(),
    lairRegionReach: num(),
    noSettleRadius: num(),
    tributeShare: num(),
    seekerPerHoard: num(),
    seekerMax: num(),
    seekerRange: num(),
    treasureValue: num(),
    grainPerSpoil: num(),
    slainImportance: num(),
    successorGap: range(),
    ageOnWaking: range(),
    lairRegionKinds: texts,
    lairUnder: text,
    lairNear: text,
    tributeWord: text,
    tributeAgain: text,
    hoardWords: map(texts),
    spoilsWord: text,
  }),
  items: list(
    obj({
      id,
      name: text,
      good: str(),
      per: count,
      kind: str(),
      spoilPerMonth: opt(share),
      spoilPerDay: opt(share),
      cooked: opt(bool()),
      forms: opt(texts),
      effects: opt(
        list(
          obj({
            kind: oneOf('combat', 'attribute', 'power'),
            value: opt(num()),
            attribute: opt(attribute),
            bonus: opt(num()),
          }),
        ),
      ),
      downsides: opt(texts),
    }),
  ),
};
