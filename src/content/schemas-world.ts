// Shapes of the world, magic-tier, creature and item files in src/content/data.
import { any, bool, list, map, num, obj, oneOf, opt, range, ref, str } from './schema';
import { attribute, count, id, share, text, texts } from './schema-fields';

export const WORLD_SCHEMAS = {
  calendar: obj({
    daysPerWeek: count,
    daysPerMonth: count,
    monthsPerYear: count,
    seasons: list(str()),
    monthNames: list(str()),
  }),
  tiers: list(
    obj({
      id: oneOf('none', 'faint', 'gifted', 'strong', 'exceptional', 'legendary'),
      minPower: count,
      maxPower: count,
      soldiers: range(),
      caps: obj({ maxDamage: count, maxAreaRadius: count, maxUsesPerDay: count }),
    }),
  ),
  biomes: obj({
    biomes: list(
      obj({
        id,
        name: text,
        color: list(num({ min: 0, max: 255 }), 3),
        fertility: count,
        wildness: count,
        travel: count,
        water: opt(oneOf('sea', 'coast', 'lake')),
        forest: opt(bool()),
      }),
    ),
    rules: obj({
      temperatureBands: list(num()),
      rainfallBands: list(num()),
      table: list(list(ref('biomes'))),
      alpineElevation: num(),
      frostFree: obj({
        biomes: list(ref('biomes')),
        minWinter: num(),
        fallback: map(ref('biomes'), 'biomes'),
      }),
      swampRainfall: num(),
      swampMinTemp: num(),
      coastReach: count,
    }),
  }),
  resources: list(
    obj({
      id,
      name: text,
      category: str(),
      good: opt(str()),
      minElevation: opt(num()),
      maxElevation: opt(num()),
      clustersPer10k: count,
      clusterSize: count,
      maxCellShare: share,
      needs: opt(map(any())),
      biomes: opt(list(ref('biomes'))),
      aquatic: opt(bool()),
    }),
  ),
  weather: list(
    obj({
      id,
      name: text,
      warmth: num(),
      seasonWeights: obj({ spring: count, summer: count, autumn: count, winter: count }),
    }),
  ),
  'great-works': obj({
    kinds: list(
      obj({
        id,
        word: text,
        thing: opt(bool()),
        names: texts,
        siteKinds: texts,
        features: texts,
        builder: obj({
          minPower: count,
          schools: list(ref('schools')),
          raceIds: list(ref('races')),
        }),
        cost: map(count),
      }),
    ),
    legendOrder: map(texts),
    realmOrder: texts,
    legendChance: share,
    realmChance: share,
    realmWealthMin: count,
    realmGapYears: count,
    maxPerSite: count,
    years: range(),
    epithets: texts,
    wallDefence: num(),
    wallRaidShare: share,
    bridgeWealth: num(),
    groveHarvest: num(),
    grovePlague: num(),
    towerKeepPower: count,
    fallPhrases: map(text),
    fallCauses: texts,
    enchant: any(),
  }),
  creatures: list(
    obj({
      id,
      name: text,
      tier: oneOf('beast', 'great', 'legendary'),
      biomes: list(ref('biomes')),
      minWildness: count,
      danger: count,
      maxAlive: count,
      spawnChance: share,
      lifespan: range(),
      raidChance: share,
      raidRange: count,
      roam: opt(count),
      names: texts,
    }),
  ),
  dragons: obj({
    creatureId: ref('creatures'),
    names: texts,
    tempers: list(any()),
    lairNames: texts,
    court: any(),
    // The other dragon fields are Story Generator history tuning, kept as forked.
    firstBy: num(),
    laterFirstBy: num(),
    cellsPerDragon: num(),
    maxAlive: num(),
    lairsApart: num(),
    lairRegionReach: num(),
    noSettleRadius: num(),
    tributeShare: num(),
    seekerPerHoard: num(),
    seekerMax: num(),
    seekerRange: num(),
    treasureValue: num(),
    grainPerSpoil: num(),
    slainImportance: num(),
    successorGap: range(),
    ageOnWaking: range(),
    lairRegionKinds: texts,
    lairUnder: text,
    lairNear: text,
    tributeWord: text,
    tributeAgain: text,
    hoardWords: map(texts),
    spoilsWord: text,
  }),
  items: list(
    obj({
      id,
      name: text,
      good: str(),
      per: count,
      kind: str(),
      spoilPerMonth: opt(share),
      spoilPerDay: opt(share),
      cooked: opt(bool()),
      forms: opt(texts),
      effects: opt(
        list(
          obj({
            kind: oneOf('combat', 'attribute', 'power'),
            value: opt(num()),
            attribute: opt(attribute),
            bonus: opt(num()),
          }),
        ),
      ),
      downsides: opt(texts),
    }),
  ),
  // Vulcan's own, not forked: the ledger text of every event type the engine may emit.
  // Slots are {actorN}, {subjectN} and data keys; the engine refuses an event that leaves one empty.
  events: list(obj({ id, importance: num({ min: 1, max: 3 }), template: text })),
  // Vulcan's own: the ground kinds a map tile can be, and the surface map's size and starting
  // ground. `art` names a frame family in the art sheets; `variants` frames end in .1, .2, ...
  terrain: obj({
    surface: obj({ width: count, height: count, ground: ref('terrain') }),
    // The surface generator's dials (src/engine/map/terrain.ts): ranges are [min, max] drawn once
    // per seed; shares are of the map's tiles; elevations are metres, temperatures degrees C.
    generator: obj({
      climates: list(
        obj({ id, name: text, weight: count, temperature: range(), rainfall: range() }),
      ),
      elevation: obj({ floor: range(), relief: range(), lapse: count, axisNoise: share }),
      noise: obj({ cell: num({ min: 2 }), octaves: num({ min: 1, max: 8 }) }),
      moisture: obj({ cell: num({ min: 2 }), low: count, span: count }),
      ridges: obj({ cell: num({ min: 2 }), weight: count }),
      rocks: list(obj({ kind: ref('terrain'), weight: count })),
      strataCell: num({ min: 2 }),
      rock: obj({
        screeKind: ref('terrain'),
        wall: share,
        scree: share,
        outcrops: share,
        outcropCell: num({ min: 2 }),
      }),
      valleyFloor: share,
      alpine: ref('biomes'),
      swamp: ref('biomes'),
      swampLowland: share,
      lowlandRain: count,
      groves: obj({
        cell: num({ min: 2 }),
        low: count,
        high: count,
        oldGrowth: obj({ cell: num({ min: 2 }), share, factor: count }),
        glades: obj({ share, factor: count }),
      }),
      start: obj({
        woodItem: ref('items'),
        stoneItem: ref('items'),
        radius: count,
        buildable: num({ min: 1 }),
        wood: num({ min: 1 }),
        stone: num({ min: 1 }),
      }),
    }),
    // The ground kind each biome's land shows.
    floors: map(ref('terrain'), 'biomes'),
    kinds: list(
      obj({
        id,
        name: text,
        art: str(),
        variants: num({ min: 1 }),
        buildable: opt(bool()),
        stone: opt(bool()),
      }),
    ),
  }),
  // Vulcan's own: what grows or lies on a tile (src/engine/map/features.ts). `density` is the
  // chance a tile of that biome holds it; trees cluster in groves; `nearRock` adds boulders below
  // rock faces.
  features: list(
    obj({
      id,
      name: text,
      kind: oneOf('tree', 'bush', 'herb', 'log', 'boulder'),
      art: str(),
      yields: ref('items'),
      amount: count,
      blocks: opt(bool()),
      clumps: opt(bool()),
      glades: opt(bool()),
      density: map(share, 'biomes'),
      nearRock: opt(obj({ reach: count, density: share })),
    }),
  ),
};
