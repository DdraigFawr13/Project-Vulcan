// Writes docs/CODEMAP.md: one line per module with its purpose and public exports. A module with more
// than LIST_MAX exports gets its count only (every thread reads the map; the engine's list alone was
// 2.7 KB, audit 2026-11-18 F14), and its names are in its index.ts and MODULE.md.
// `--check` fails when the committed map is stale. Purpose is the first paragraph line of MODULE.md.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { dirs, isMain, rel, root } from './lib.mjs';

const out = path.join(root, 'docs/CODEMAP.md');
const LIST_MAX = 15;

function purpose(folder) {
  const file = path.join(folder, 'MODULE.md');
  if (!existsSync(file)) return '(no MODULE.md)';
  const line = readFileSync(file, 'utf8')
    .split('\n')
    .find((l) => l.trim() && !l.startsWith('#'));
  return (line ?? '').trim();
}

const exportsOf = (folder) => namesIn(path.join(folder, 'index.ts'), new Set());

// The names a file exports; `export * from` and `export type * from` are followed into the file
// they name, so a hub that passes a system's surface on whole still lists its names.
function namesIn(file, seen) {
  if (!existsSync(file) || seen.has(file)) return [];
  seen.add(file);
  const text = readFileSync(file, 'utf8');
  const names = [
    ...text.matchAll(
      /export\s+(?:declare\s+)?(?:async\s+)?(?:abstract\s+)?(?:const\s+enum|const|let|function\*?|class|type|interface|enum)\s+(\w+)/g,
    ),
  ].map((m) => m[1]);
  for (const m of text.matchAll(/export\s+(?:type\s+)?\{([^}]*)\}/g))
    names.push(
      ...m[1]
        .split(',')
        .map((n) =>
          n
            .trim()
            .replace(/^type\s+/, '')
            .split(/\s+as\s+/)
            .at(-1),
        )
        .filter(Boolean),
    );
  for (const m of text.matchAll(/export\s+(?:type\s+)?\*\s+(?:as\s+(\w+)\s+)?from\s+'([^']+)'/g))
    if (m[1]) names.push(m[1]);
    else if (m[2].startsWith('.'))
      names.push(...namesIn(path.resolve(path.dirname(file), m[2]), seen));
    else names.push(`* from ${m[2]}`);
  return [...new Set(names)].sort();
}

function exportsLine(folder, names) {
  if (!names.length) return '';
  if (names.length > LIST_MAX)
    return ` Exports: ${names.length} names (see \`${rel(folder)}/index.ts\`).`;
  return ` Exports: ${names.join(', ')}.`;
}

export function codemap() {
  const rows = [];
  for (const layer of dirs(path.join(root, 'src')))
    for (const folder of [layer, ...dirs(layer).filter((d) => !d.endsWith(`${path.sep}data`))]) {
      const names = exportsOf(folder);
      rows.push(`- \`${rel(folder)}/\` ${purpose(folder)}${exportsLine(folder, names)}`);
    }
  return `# Code map\n\nGenerated by \`npm run codemap\`; don't edit. Read a module's \`MODULE.md\` before its code.\n\n${rows.join('\n')}\n`;
}

if (isMain(import.meta.url)) {
  const text = codemap();
  if (process.argv.includes('--check')) {
    const current = existsSync(out) ? readFileSync(out, 'utf8') : '';
    if (current !== text) {
      process.stderr.write('docs/CODEMAP.md is stale; run `npm run codemap`.\n');
      process.exitCode = 1;
    } else process.stdout.write('Code map is current.\n');
  } else {
    writeFileSync(out, text);
    process.stdout.write('Wrote docs/CODEMAP.md.\n');
  }
}
