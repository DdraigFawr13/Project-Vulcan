// Writes docs/CODEMAP.md: one line per module with its purpose and public exports.
// `--check` fails when the committed map is stale. Purpose is the first paragraph line of MODULE.md.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { dirs, isMain, rel, root } from './lib.mjs';

const out = path.join(root, 'docs/CODEMAP.md');

function purpose(folder) {
  const file = path.join(folder, 'MODULE.md');
  if (!existsSync(file)) return '(no MODULE.md)';
  const line = readFileSync(file, 'utf8')
    .split('\n')
    .find((l) => l.trim() && !l.startsWith('#'));
  return (line ?? '').trim();
}

function exportsOf(folder) {
  const file = path.join(folder, 'index.ts');
  if (!existsSync(file)) return [];
  const text = readFileSync(file, 'utf8');
  const names = [
    ...text.matchAll(
      /export\s+(?:declare\s+)?(?:async\s+)?(?:abstract\s+)?(?:const\s+enum|const|let|function\*?|class|type|interface|enum)\s+(\w+)/g,
    ),
  ].map((m) => m[1]);
  for (const m of text.matchAll(/export\s+(?:type\s+)?\{([^}]*)\}/g))
    names.push(
      ...m[1]
        .split(',')
        .map((n) =>
          n
            .trim()
            .replace(/^type\s+/, '')
            .split(/\s+as\s+/)
            .at(-1),
        )
        .filter(Boolean),
    );
  for (const m of text.matchAll(/export\s+\*\s+(?:as\s+(\w+)\s+)?from\s+'([^']+)'/g))
    names.push(m[1] ?? `* from ${m[2]}`);
  return [...new Set(names)].sort();
}

export function codemap() {
  const rows = [];
  for (const layer of dirs(path.join(root, 'src')))
    for (const folder of [layer, ...dirs(layer).filter((d) => !d.endsWith(`${path.sep}data`))]) {
      const names = exportsOf(folder);
      rows.push(
        `- \`${rel(folder)}/\` ${purpose(folder)}${names.length ? ` Exports: ${names.join(', ')}.` : ''}`,
      );
    }
  return `# Code map\n\nGenerated by \`npm run codemap\`; don't edit. Read a module's \`MODULE.md\` before its code.\n\n${rows.join('\n')}\n`;
}

if (isMain(import.meta.url)) {
  const text = codemap();
  if (process.argv.includes('--check')) {
    const current = existsSync(out) ? readFileSync(out, 'utf8') : '';
    if (current !== text) {
      process.stderr.write('docs/CODEMAP.md is stale; run `npm run codemap`.\n');
      process.exitCode = 1;
    } else process.stdout.write('Code map is current.\n');
  } else {
    writeFileSync(out, text);
    process.stdout.write('Wrote docs/CODEMAP.md.\n');
  }
}
